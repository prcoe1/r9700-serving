#!/usr/bin/env python3
"""Thinking-ON scenario probe for thinking-enabled clients (Open WebUI,
custom harnesses).

The 2026-08-20 template-stability test covered thinking-OFF turns only.
Thinking-ON history is a different render path (the real CoT re-wrapped in
`...


`) and has four properties this
probe checks against the live server:

1. functional: `reasoning` + `content` split, correct answer, no degeneration
2. byte-identity: rendering the 2-turn prompt from echoed history
   (`reasoning` + `content`) must equal the 1-turn prompt + the exact raw
   generated bytes — the prefix-cache invariance property (would matter the
   moment #45238 is fixed, and keeps the model's view of its own history
   stable regardless)
3. coherence: 3-turn thinking-on conversation, secret retained; history
   reasoning echoed once as `reasoning` (vLLM native) and once as
   `reasoning_content` (Open WebUI convention)
4. tool calling with thinking on: XML tool_call parsed, finish_reason

Run inside the container (needs jinja2 + transformers, both present):
    just exec python3 /workspace/benchmarks/thinking_probe.py

Requires a reachable vLLM server (default http://localhost:8180).
"""
import json
import sys
import time

import jinja2
import requests
from transformers import AutoTokenizer

BASE = "http://localhost:8180"
MODEL = "qwen3.8-27b"
TEMPLATE = "/app/chat-templates/qwen.jinja"
MODEL_DIR = "/home/philip/models-local/Qwen3.8-27B-FP8-kvscales"
SECRET = "purple comet 77"

PASS = 0
FAIL = 0


def check(name, ok, detail=""):
    global PASS, FAIL
    PASS, FAIL = (PASS + 1, FAIL) if ok else (PASS, FAIL + 1)
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f" — {detail}" if detail else ""),
          flush=True)


def render(messages, agp=True, **kw):
    """Render the prompt exactly as the server does (same jinja text, same
    variables)."""
    tpl = jinja2.Template(open(TEMPLATE).read(),
                          undefined=jinja2.ChainableUndefined)
    return tpl.render(messages=messages, tools=None,
                      add_generation_prompt=agp, **kw)


def chat(messages, max_tokens=256, tools=None, logprobs=None, **kw):
    body = {
        "model": MODEL,
        "messages": messages,
        "max_tokens": max_tokens,
        "temperature": 0,
        "chat_template_kwargs": {"enable_thinking": True, **kw},
    }
    if tools:
        body["tools"] = tools
    if logprobs is not None:
        body["logprobs"] = logprobs
    t0 = time.time()
    r = requests.post(BASE + "/v1/chat/completions", json=body, timeout=600)
    if r.status_code != 200:
        raise SystemExit(f"HTTP {r.status_code}: {r.text[:300]}")
    return r.json(), time.time() - t0


def main() -> None:
    tok = AutoTokenizer.from_pretrained(MODEL_DIR)

    print("1. functional (thinking on)", flush=True)
    u1 = ("Think carefully, step by step, then answer in one line: "
          "A bat and a ball cost $1.10 in total. The bat costs $1.00 more "
          "than the ball. How much does the ball cost?")
    d, dt = chat([{"role": "user", "content": u1}], max_tokens=300)
    msg = d["choices"][0]["message"]
    reasoning, content = msg.get("reasoning") or "", msg.get("content") or ""
    check("reasoning field non-empty", len(reasoning) > 50,
          f"{len(reasoning)} chars, {dt:.1f}s, finish={d['choices'][0]['finish_reason']}")
    check("answer correct", "0.05" in content or "5 cent" in content.lower(),
          repr(content[:100]))
    check("no obvious degeneration",
          reasoning.count(reasoning[:20]) < 5 if len(reasoning) > 20 else True,
          f"reasoning head repeats {reasoning.count(reasoning[:20])}x")

    print("2. byte-identity of echoed thinking history", flush=True)
    d2, _ = chat([{"role": "user", "content": u1}], max_tokens=300, logprobs=1)
    lp = d2["choices"][0]["logprobs"]["content"]
    raw = bytes(b for t in lp for b in t["bytes"]).decode("utf-8", "replace")

    # Isolate (a) the generation prompt and (b) the re-rendered assistant
    # turn by subtracting the no-prompt render from the with-prompt render —
    # no suffix guessing.
    p_u1 = render([{"role": "user", "content": u1}], agp=False,
                  enable_thinking=True)
    genprompt = render([{"role": "user", "content": u1}], agp=True,
                       enable_thinking=True)[len(p_u1):]
    p_two = render([{"role": "user", "content": u1},
                    {"role": "assistant", "content": content,
                     "reasoning": reasoning}],
                   agp=False, enable_thinking=True)
    astrender = p_two[len(p_u1):]

    check("echoed turn == generation prompt + raw generated bytes",
          astrender == genprompt + raw,
          f"astrender={len(astrender)}B expected={len(genprompt + raw)}B")
    if astrender != genprompt + raw:
        exp = genprompt + raw
        n = min(len(astrender), len(exp))
        i = next((k for k in range(n) if astrender[k] != exp[k]), n)
        print(f"    first diff @ {i}:\n"
              f"      ast={astrender[max(0, i - 40):i + 40]!r}\n"
              f"      exp={exp[max(0, i - 40):i + 40]!r}")
        print(f"    len ast={len(astrender)} exp={len(exp)}\n"
              f"      ast tail={astrender[-60:]!r}\n"
              f"      exp tail={exp[-60:]!r}")

    u2 = "What is 6 times 7? Answer with just the number."
    hist = [{"role": "user", "content": u1},
            {"role": "assistant", "content": content, "reasoning": reasoning},
            {"role": "user", "content": u2}]
    d3, _ = chat(hist, max_tokens=128)
    check("echoed turn still answers", "42" in (d3["choices"][0]["message"].get("content") or ""),
          repr((d3["choices"][0]["message"].get("content") or "")[:60]))

    print("3. multi-turn coherence (thinking on, mixed echo fields)", flush=True)
    history = [{"role": "system", "content": "You are a helpful assistant."},
               {"role": "user", "content": f"Remember this secret: {SECRET}. Acknowledge briefly."}]
    for i, field in enumerate(["reasoning", "reasoning_content"], start=1):
        d, _ = chat(history, max_tokens=400)
        m = d["choices"][0]["message"]
        history.append({"role": "assistant", "content": m.get("content") or "",
                        **{field: m.get("reasoning") or ""}})
        check(f"turn {i} ({field} echo): reasoning present",
              bool(m.get("reasoning")), f"{len(m.get('reasoning') or '')} chars")
        history.append({"role": "user", "content": "Still remember the secret? Hold it in mind."})
    # thinking-on: the CoT consumes the token budget, so give the answer
    # room (a small max_tokens here would truncate to an empty content).
    d, _ = chat(history[:-1], max_tokens=500)
    out = d["choices"][0]["message"].get("content") or ""
    check("secret retained after 2 thinking-on turns", SECRET in out, repr(out[:80]))

    print("4. tool calling (thinking on)", flush=True)
    tools = [{"type": "function", "function": {
        "name": "get_weather",
        "description": "Get the weather for a city",
        "parameters": {"type": "object",
                       "properties": {"city": {"type": "string"}},
                       "required": ["city"]}}}]
    d, _ = chat([{"role": "user",
                  "content": "What's the weather in Paris? Use the tool."}],
                max_tokens=300, tools=tools)
    ch = d["choices"][0]
    tcs = ch["message"].get("tool_calls") or []
    ok = ch["finish_reason"] == "tool_calls" and tcs and \
        tcs[0]["function"]["name"] == "get_weather" and \
        json.loads(tcs[0]["function"]["arguments"]).get("city") == "Paris"
    check("tool_call parsed with thinking on", ok,
          f"finish={ch['finish_reason']} tc={tcs[0]['function']['name'] if tcs else None}")

    print(f"\n{'PASS' if FAIL == 0 else 'FAIL'}: {PASS} passed, {FAIL} failed",
          flush=True)
    sys.exit(1 if FAIL else 0)


if __name__ == "__main__":
    main()
